import assert from "node:assert/strict";
import { test } from "node:test";
import { chromium } from "playwright-core";

const base = process.env.PREVIEW_BASE ?? "http://localhost:3000";
if (!["localhost", "127.0.0.1"].includes(new URL(base).hostname)) throw new Error("Browser checks must target a local server");

test("Coral Cove personalization previews edits and saves the correct draft", { timeout: 90_000 }, async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    let saved;
    await page.route("**/api/personalization/coral-cove", async (route) => {
      saved = route.request().postDataJSON();
      await route.fulfill({ json: { updatedAt: new Date().toISOString() } });
    });
    await page.goto(`${base}/personalize/coral-cove`, { waitUntil: "domcontentloaded" });
    await page.getByLabel("Business name").fill("Island Haven");
    await page.getByLabel("Introduction headline").fill("Your island escape");
    const preview = page.frameLocator('iframe[title="Coral Cove home page preview"]');
    await preview.getByRole("heading", { name: "Island Haven" }).waitFor();
    await preview.getByRole("heading", { name: "Your island escape" }).waitFor();
    await page.getByText("Home page sections", { exact: true }).click();
    await page.getByLabel("Travel step 1 title").fill("Arrive by ferry");
    await page.getByLabel("Reef section heading").fill("Meet the sea");
    await preview.getByText("Arrive by ferry", { exact: true }).waitFor();
    await preview.getByRole("heading", { name: "Meet the sea", exact: true }).waitFor();
    await page.getByText("Gallery photos", { exact: true }).click();
    const image = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aL8AAAAASUVORK5CYII=", "base64");
    await page.getByLabel("Gallery image").selectOption("snorkeler");
    await page.locator("details").filter({ has: page.locator("summary").filter({ hasText: /^Gallery photos$/ }) }).getByLabel("Photo description").fill("Our reef photo");
    await page.getByLabel("Replace gallery photo").setInputFiles({ name: "reef.png", mimeType: "image/png", buffer: image });
    await page.getByLabel("Use the gallery's snorkeler photo in the home-page reef section").check();
    await page.getByLabel("Gallery image").selectOption("coral");
    await page.locator("details").filter({ has: page.locator("summary").filter({ hasText: /^Gallery photos$/ }) }).getByLabel("Photo description").fill("Our coral photo");
    await page.getByLabel("Replace gallery photo").setInputFiles({ name: "coral.png", mimeType: "image/png", buffer: image });
    await page.getByLabel("Use the matching gallery photos in the home-page photo strip").check();
    await page.getByRole("button", { name: "Preview home photos" }).click();
    await preview.getByAltText("Our reef photo").waitFor();
    await preview.getByAltText("Our coral photo").waitFor();
    await page.getByLabel("Use the matching gallery photos in the home-page photo strip").uncheck();
    await preview.getByAltText("Our coral photo").waitFor({ state: "hidden" });
    await page.getByLabel("Use the matching gallery photos in the home-page photo strip").check();
    await page.getByText("Guest reviews", { exact: true }).click();
    await page.getByLabel("Review text").fill("A memorable stay");
    await page.getByLabel("Guest name").fill("A visitor");
    await preview.getByText("A memorable stay", { exact: false }).waitFor();
    await page.getByLabel("Show guest reviews").uncheck();
    await preview.getByText("A memorable stay", { exact: false }).waitFor({ state: "hidden" });
    await page.getByLabel("Show guest reviews").check();
    await preview.getByText("A memorable stay", { exact: false }).waitFor();
    await page.getByText("Villa content", { exact: true }).click();
    await page.getByLabel("Villa name").fill("Reef Suite");
    await page.getByLabel("Nightly price (PHP)").fill("12345");
    await page.getByLabel("Villa amenities").fill("Private deck\nOcean view");
    await page.getByRole("button", { name: "Preview this villa" }).click();
    await preview.getByRole("heading", { name: "Reef Suite", exact: true }).waitFor();
    await preview.getByText("Private deck", { exact: true }).waitFor();
    await page.getByLabel("Preview page").selectOption("villas");
    await preview.getByRole("heading", { name: "Reef Suite", exact: true }).first().waitFor();
    await page.getByText("Contact questions", { exact: true }).click();
    await page.getByLabel("Question topic").selectOption("cancellation");
    await page.getByLabel("Question", { exact: true }).fill("Can I change my stay?");
    await page.getByLabel("Answer", { exact: true }).fill("Please contact our team.");
    await page.getByRole("button", { name: "Preview contact page" }).click();
    await preview.locator("summary").filter({ hasText: "Can I change my stay?" }).click();
    await preview.getByText("Please contact our team.", { exact: true }).waitFor();
    await page.getByRole("button", { name: "mobile", exact: true }).click();
    assert.equal(await preview.locator("body").evaluate(() => innerWidth), 390);
    await page.getByRole("button", { name: "Save draft" }).click();
    await page.getByRole("status").getByText("Draft saved. Save each changed villa or gallery photo separately.").waitFor();
    assert.equal(saved.draft.template, "coral-cove");
    assert.equal(saved.draft.home.headline, "Your island escape");
    assert.equal(saved.draft.villas["overwater-villa"].name, "Reef Suite");
    assert.equal(saved.draft.villas["overwater-villa"].price, 12345);
    assert.equal(saved.draft.homeSections.travel.first.title, "Arrive by ferry");
    assert.equal(saved.draft.homeSections.useGalleryReef, true);
    assert.equal(saved.draft.homeSections.useGalleryStrip, true);
    assert.equal(saved.draft.reviews.first.quote, "A memorable stay");
    await page.getByRole("button", { name: "Reset changes" }).click();
    assert.equal(await page.getByLabel("Business name").inputValue(), "");
  } finally { await browser.close(); }
});
