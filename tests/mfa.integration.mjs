import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { test } from "node:test";
import { PrismaClient } from "@prisma/client";
import { testDatabaseConfig } from "../scripts/personalization-test-config.mjs";
import { beginMfaEnrollment, confirmMfaEnrollment, consumeMfaCode, MfaError } from "../src/lib/mfa.ts";
import { totp } from "../src/lib/mfa-crypto.ts";

test("MFA enrollment, recovery and rotation use atomic isolated database operations", async t => {
  const { target } = testDatabaseConfig();
  const db = new PrismaClient({ datasources: { db: { url: target } } });
  const ids = [randomUUID(), randomUUID()];
  const original = process.env.MFA_ENCRYPTION_KEY;
  process.env.MFA_ENCRYPTION_KEY = randomBytes(32).toString("base64");
  t.after(async () => { try { await db.user.deleteMany({ where: { id: { in: ids } } }); } finally { await db.$disconnect(); if (original === undefined) delete process.env.MFA_ENCRYPTION_KEY; else process.env.MFA_ENCRYPTION_KEY = original; } });
  await db.user.createMany({ data: ids.map((id, index) => ({ id, email: `${id}@example.test`, role: index ? "CLIENT" : "ADMIN", emailVerified: new Date() })) });
  await assert.rejects(beginMfaEnrollment(ids[1], "", db), MfaError);
  const setup = await beginMfaEnrollment(ids[0], "", db);
  let stored = await db.mfaCredential.findUniqueOrThrow({ where: { userId: ids[0] } });
  assert.equal(stored.enabledAt, null);
  assert.ok(!stored.pendingSecret.includes(setup.secret));
  await assert.rejects(confirmMfaEnrollment(ids[0], "invalid", db), MfaError);
  const code = totp(setup.secret, Math.floor(Date.now() / 30000));
  const codes = await confirmMfaEnrollment(ids[0], code, db);
  assert.equal(codes.length, 10);
  await assert.rejects(consumeMfaCode(ids[0], code, db), MfaError);
  const results = await Promise.allSettled([consumeMfaCode(ids[0], codes[0], db), consumeMfaCode(ids[0], codes[0], db)]);
  assert.equal(results.filter(result => result.status === "fulfilled").length, 1);
  assert.equal(results.filter(result => result.status === "rejected").length, 1);
  stored = await db.mfaCredential.findUniqueOrThrow({ where: { userId: ids[0] } });
  assert.equal(stored.recoveryHashes.length, 9);
  assert.equal(stored.version, 1);
  assert.ok((await db.user.findUniqueOrThrow({ where: { id: ids[0] } })).sessionsValidAfter);
  await assert.rejects(beginMfaEnrollment(ids[0], "", db), MfaError);
  const replacement = await beginMfaEnrollment(ids[0], codes[1], db);
  assert.equal((await db.mfaCredential.findUniqueOrThrow({ where: { userId: ids[0] } })).secret, stored.secret);
  await db.mfaCredential.update({ where: { userId: ids[0] }, data: { pendingExpiresAt: new Date(Date.now() - 1000) } });
  await assert.rejects(confirmMfaEnrollment(ids[0], totp(replacement.secret, Math.floor(Date.now() / 30000)), db), MfaError);
  const fresh = await beginMfaEnrollment(ids[0], codes[2], db);
  const nextCodes = await confirmMfaEnrollment(ids[0], totp(fresh.secret, Math.floor(Date.now() / 30000)), db);
  assert.equal((await db.mfaCredential.findUniqueOrThrow({ where: { userId: ids[0] } })).version, 2);
  await assert.rejects(consumeMfaCode(ids[0], codes[3], db), MfaError);
  assert.equal(await consumeMfaCode(ids[0], nextCodes[0], db), 2);
  await assert.rejects(consumeMfaCode(ids[0], nextCodes[1], db, Date.now() - 60_000), MfaError);
  assert.equal(await consumeMfaCode(ids[0], nextCodes[1], db, Date.now()), 2);
  await db.user.update({ where: { id: ids[0] }, data: { disabled: true } });
  await assert.rejects(consumeMfaCode(ids[0], nextCodes[1], db), MfaError);
});
