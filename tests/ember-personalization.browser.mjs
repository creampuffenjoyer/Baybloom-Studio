import assert from "node:assert/strict";
import { test } from "node:test";
import { chromium } from "playwright-core";

const base = process.env.PREVIEW_BASE ?? "http://localhost:3000";
if (!["localhost", "127.0.0.1"].includes(new URL(base).hostname)) throw new Error("Browser checks must target a local server");

test("Ember & Salt editor previews changes and saves its own draft", { timeout: 90_000 }, async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    let saved;
    await page.route("**/api/personalization/ember-and-salt", async (route) => {
      if (route.request().method() === "PUT") {
        saved = route.request().postDataJSON();
        await route.fulfill({ json: { updatedAt: new Date().toISOString() } });
      } else await route.fulfill({ json: { draft: saved?.draft ?? null, hasPhoto: false, updatedAt: new Date().toISOString() } });
    });
    await page.goto(`${base}/personalize/ember-and-salt`, { waitUntil: "domcontentloaded" });
    await page.getByLabel("Business name").fill("Lake Haven");
    await page.getByLabel("Home page headline").fill("Find your calm");
    await page.getByLabel("Email", { exact: true }).fill("hello@lake.example");
    const preview = page.frameLocator('iframe[title="Ember & Salt home page preview"]');
    await preview.getByRole("heading", { name: "Find your calm" }).waitFor();
    await preview.getByText("hello@lake.example").waitFor();
    await page.getByText("More website wording", { exact: true }).click();
    await page.getByLabel("Find wording").fill("The bar keeps seats free");
    await page.getByLabel("Original wording").selectOption({ label: "The bar keeps seats free." });
    await page.getByLabel("Replacement wording").fill("Meet us at the bar.");
    await preview.getByRole("heading", { name: "Meet us at the bar." }).waitFor();
    await page.getByText("Restaurant story", { exact: true }).click();
    await page.getByLabel("Story heading").fill("Our garden story");
    await page.getByLabel("Timeline description").fill("The restaurant opens.");
    await page.getByRole("button", { name: "Preview story" }).click();
    await preview.getByRole("heading", { name: "Our garden story" }).waitFor();
    await preview.getByText("The restaurant opens.").waitFor();
    await page.getByText("Menus and dishes", { exact: true }).click();
    assert.equal(await page.getByLabel("Vegetarian", { exact: true }).isChecked(), true);
    await page.getByLabel("Dish name", { exact: true }).fill("Garden plate");
    assert.equal(await page.getByLabel("Vegetarian", { exact: true }).isChecked(), false);
    await page.getByLabel("Dish ingredients and description").fill("Roasted vegetables");
    await page.getByLabel("Dish price (PHP)").fill("450");
    await page.getByRole("button", { name: "Preview menu" }).click();
    await preview.getByText("Garden plate", { exact: true }).waitFor();
    await preview.getByLabel("Search dishes").fill("Garden plate");
    await preview.getByText("Garden plate", { exact: true }).waitFor();
    await page.getByText("Private dining spaces", { exact: true }).click();
    await page.getByLabel("Space name").fill("Garden Room");
    await page.getByRole("button", { name: "Preview private dining" }).click();
    await preview.getByRole("heading", { name: "Garden Room", exact: true }).waitFor();
    await page.getByText("Opening hours", { exact: true }).click();
    await page.getByLabel("Hours", { exact: true }).fill("5 pm to 10 pm");
    await page.getByRole("button", { name: "Preview visit" }).click();
    await preview.getByText("5 pm to 10 pm", { exact: true }).first().waitFor();
    await page.getByText("Press quotes", { exact: true }).click();
    await page.getByLabel("Show press quotes").uncheck();
    await page.getByRole("button", { name: "Preview quotes" }).click();
    await preview.getByRole("region", { name: "What people say" }).waitFor({ state: "hidden" });
    await page.getByText("Featured dishes", { exact: true }).click();
    await page.getByLabel("Featured dish name").fill("Grilled vegetables");
    await preview.getByRole("heading", { name: "Grilled vegetables", exact: true }).waitFor();
    await page.getByText("Website photos", { exact: true }).click();
    await page.getByLabel("Website photo", { exact: true }).selectOption("room");
    await page.getByLabel("Photo description").fill("Our restaurant room");
    await page.getByLabel("Replace website photo").setInputFiles({ name: "room.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aL8AAAAASUVORK5CYII=", "base64") });
    await page.getByRole("button", { name: "Preview visit" }).click();
    await preview.getByAltText("Our restaurant room").waitFor();
    await page.getByLabel("Preview page").selectOption("home");
    await page.getByLabel("Home page photo").setInputFiles({ name: "sample.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aL8AAAAASUVORK5CYII=", "base64") });
    await preview.locator('img[alt="Your selected hero image"]').waitFor();
    await page.getByRole("button", { name: "mobile", exact: true }).click();
    assert.equal(await preview.locator("body").evaluate(() => innerWidth), 390);
    await page.getByRole("button", { name: "Save draft" }).click();
    await page.getByRole("status").getByText("Draft saved. Save each changed website photo separately.").waitFor();
    assert.equal(saved.draft.template, "ember-and-salt");
    assert.equal(saved.photo.action, "replace");
    assert.equal(saved.draft.emberDishes["dinner:0:0"].price, 450);
    assert.deepEqual(saved.draft.emberDishes["dinner:0:0"].diet, []);
    assert.equal(saved.draft.emberSpaces["back-room"].name, "Garden Room");
    assert.equal(saved.draft.emberStory.chapters.first.text, "The restaurant opens.");
    assert.equal(saved.draft.emberCopy["The bar keeps seats free."], "Meet us at the bar.");
    assert.equal(saved.draft.emberPressHidden, true);
    assert.equal(saved.draft.emberPhotoAlt.room, "Our restaurant room");
    await page.getByRole("button", { name: "Reset changes" }).click();
    await page.getByRole("button", { name: "Load saved draft" }).click();
    await preview.getByRole("heading", { name: "Find your calm" }).waitFor();
    await preview.getByRole("heading", { name: "Meet us at the bar." }).waitFor();
  } finally { await browser.close(); }
});
