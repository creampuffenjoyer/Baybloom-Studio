import assert from "node:assert/strict";
import { test } from "node:test";
import { chromium } from "playwright-core";

const base = process.env.PREVIEW_BASE ?? "http://localhost:3000";
if (!["localhost", "127.0.0.1"].includes(new URL(base).hostname)) throw new Error("Browser checks must target a local server");

test("Pine Ridge editor previews both seasons and saves its own draft", { timeout: 90_000 }, async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    let saved;
    await page.route("**/api/personalization/pine-ridge-lodge", async (route) => {
      saved = route.request().postDataJSON();
      await route.fulfill({ json: { updatedAt: new Date().toISOString() } });
    });
    await page.goto(`${base}/personalize/pine-ridge-lodge`, { waitUntil: "domcontentloaded" });
    await page.getByLabel("Business name").fill("Mountain Haven");
    await page.getByLabel("Home page headline").fill("Your mountain escape");
    await page.getByLabel("Welcome message").fill("Welcome to the mountains.");
    const preview = page.frameLocator('iframe[title="Pine Ridge Lodge home page preview"]');
    await preview.getByRole("heading", { name: "Your mountain escape" }).waitFor();
    await page.getByText("More website wording", { exact: true }).click();
    await page.getByLabel("Find wording").fill("Supper at the long table");
    await page.getByLabel("Replacement wording").fill("Dinner by the fire");
    await preview.getByRole("heading", { name: "Dinner by the fire", exact: true }).waitFor();
    await page.getByText("Seasonal content", { exact: true }).click();
    await page.getByLabel("Season months").fill("December through March");
    await page.getByLabel("Season", { exact: true }).selectOption("summer");
    await page.getByLabel("Season months").fill("June through September");
    await preview.getByRole("button", { name: "Summer", exact: true }).click();
    await preview.getByRole("heading", { name: "Your mountain escape" }).waitFor();
    await preview.getByRole("button", { name: "Winter", exact: true }).click();
    await preview.getByRole("heading", { name: "Your mountain escape" }).waitFor();
    await page.getByText("Sample booking extras", { exact: true }).click();
    await page.getByLabel("Extra name").fill("Mountain lift access");
    await page.getByLabel("Extra price (CAD)").fill("130");
    await page.getByText("Page introductions", { exact: true }).click();
    await page.getByLabel("Page heading").fill("Lodge accommodation");
    await page.getByRole("button", { name: "Preview selected page" }).click();
    await preview.getByRole("heading", { name: "Lodge accommodation", exact: true }).waitFor();
    await page.getByText("Room content", { exact: true }).click();
    await page.getByLabel("Room name").fill("Forest Room");
    await page.getByLabel("Nightly price (CAD)").fill("250");
    await page.getByRole("button", { name: "Preview room" }).click();
    await preview.getByRole("heading", { name: "Forest Room", exact: true }).waitFor();
    await page.getByText("Website photos", { exact: true }).click();
    await page.getByLabel("Website photo", { exact: true }).selectOption("twin-room");
    await page.getByLabel("Photo description").fill("Our forest bedroom");
    await page.getByLabel("Replace website photo").setInputFiles({ name: "room.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aL8AAAAASUVORK5CYII=", "base64") });
    await preview.getByAltText("Our forest bedroom").first().waitFor();
    await page.getByText("Activities content", { exact: true }).click();
    await page.getByLabel("Activity name").fill("Mountain adventure");
    await page.getByRole("button", { name: "Preview activities" }).click();
    await preview.getByText("Mountain adventure", { exact: true }).first().waitFor();
    await page.getByText("Dining menu", { exact: true }).click();
    await page.getByLabel("Dish name").fill("Forest stew");
    await page.getByRole("button", { name: "Preview dining" }).click();
    await preview.getByText("Forest stew", { exact: true }).waitFor();
    await page.getByText("Journal content", { exact: true }).click();
    await page.getByLabel("Article title").fill("Our mountain guide");
    await page.getByRole("button", { name: "Preview article" }).click();
    await preview.getByRole("heading", { name: "Our mountain guide", exact: true }).waitFor();
    await page.getByRole("button", { name: "mobile", exact: true }).click();
    assert.equal(await preview.locator("body").evaluate(() => innerWidth), 390);
    await page.getByRole("button", { name: "Save draft" }).click();
    await page.getByRole("status").getByText("Draft saved. Save each changed website photo separately.").waitFor();
    assert.equal(saved.draft.template, "pine-ridge-lodge");
    assert.equal(saved.draft.business.name, "Mountain Haven");
    assert.equal(saved.draft.pineRooms["trapper-twin"].price, 250);
    assert.equal(saved.draft.pineActivities["ridge-ski"].name, "Mountain adventure");
    assert.equal(saved.draft.pineMenu.first.name, "Forest stew");
    assert.equal(saved.draft.pinePosts["how-to-dress-for-a-bluebird-day"].title, "Our mountain guide");
    assert.equal(saved.draft.pinePhotoAlt["twin-room"], "Our forest bedroom");
    assert.equal(saved.draft.pineSeasons.winter.months, "December through March");
    assert.equal(saved.draft.pineSeasons.summer.months, "June through September");
    assert.equal(saved.draft.pineCopy["Supper at the long table"], "Dinner by the fire");
    assert.equal(saved.draft.pineExtras.lift.price, 130);
    assert.equal(saved.draft.pinePages.rooms.heading, "Lodge accommodation");
  } finally { await browser.close(); }
});
