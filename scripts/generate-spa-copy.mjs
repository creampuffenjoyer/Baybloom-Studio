import { readdir, readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
const keys = new Set();
try {
  const previous = await readFile("src/lib/personalization/spa-copy-keys.ts", "utf8");
  const match = previous.match(/export const SPA_COPY_KEYS = ([\s\S]+) as const;\s*$/);
  if (!match) throw new Error("Cannot parse existing spa copy catalog");
  for (const key of JSON.parse(match[1])) keys.add(key);
} catch (error) { if (error.code !== "ENOENT") throw error; }
for (const area of ["pages"]) for (const file of await readdir(`src/templates/still-water-spa/${area}`)) {
  if (!file.endsWith(".tsx") || file === "credits.tsx") continue;
  const path = `src/templates/still-water-spa/${area}/${file}`;
  let text = await readFile(path, "utf8");
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const edits = [];
  function visit(node) {
    if (ts.isArrayLiteralExpression(node) && node.elements.length === 2 && node.elements.every(ts.isStringLiteral)) for (const element of node.elements) keys.add(element.text);
    if (ts.isJsxText(node)) {
      const value = node.text.replace(/\s+/g, " ").trim();
      if (/[a-zA-Z]/.test(value) && !/sample|demonstration|no payment|no appointment|no message|health|pregnan/i.test(value)) {
        keys.add(value); edits.push({ start: node.getFullStart(), end: node.end, value: `{copy(${JSON.stringify(value)})}` });
      }
    }
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "copy" && ts.isStringLiteral(node.arguments[0])) keys.add(node.arguments[0].text);
    ts.forEachChild(node, visit);
  }
  visit(source);
  for (const edit of edits.sort((a,b) => b.start-a.start)) text = text.slice(0,edit.start)+edit.value+text.slice(edit.end);
  if (edits.length) {
    text = text.replace(/^"use client";\s*/, "");
    if (!text.includes('import { useSpaCopy }')) text = 'import { useSpaCopy } from "../copy";\n'+text;
    if (!text.includes("const copy = useSpaCopy();")) text = text.replace(/(export function \w+\([^\n]*\) \{)/, "$1\n  const copy = useSpaCopy();");
    await writeFile(path, '"use client";\n'+text);
  }
}
await writeFile("src/lib/personalization/spa-copy-keys.ts", `// Generated by scripts/generate-spa-copy.mjs.\nexport const SPA_COPY_KEYS = ${JSON.stringify([...keys].sort(),null,2)} as const;\n`);
