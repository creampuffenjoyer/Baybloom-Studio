// Regenerate the editable English interface strings from Lumen Lake source.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

async function files(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const name = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...await files(name));
    else if (name.endsWith(".tsx")) result.push(name);
  }
  return result;
}
const strings = new Set();
// These are the stable labels of the villa comparison table, translated via t(label).
for (const label of ["From, per night", "Setting", "Size", "Sleeps", "Bedrooms", "Private jetty", "Own sauna"]) strings.add(label);
// The booking flow passes these values through t() dynamically.
for (const question of ["When will you come?", "Where would you like to stay?", "Who should we expect?", "Shall we hold it for you?"]) strings.add(question);
for (const label of ["Villas", "Experiences", "Virtual tour", "Contact"]) strings.add(label);
// Keep previously accepted keys so an old saved draft remains readable if
// template copy changes in a later release.
try {
  const previous = await readFile("src/lib/personalization/lumen-copy-keys.ts", "utf8");
  const match = previous.match(/export const LUMEN_COPY_KEYS = ([\s\S]+) as const;\s*$/);
  if (!match) throw new Error("Cannot parse existing Pine copy catalog");
  for (const text of JSON.parse(match[1])) strings.add(text);
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
for (const file of await files("src/templates/lumen-lake-villas")) {
  const source = ts.createSourceFile(file, await readFile(file, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const visit = (node) => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "t" && node.arguments.length === 1 && ts.isStringLiteral(node.arguments[0])) strings.add(node.arguments[0].text);
    ts.forEachChild(node, visit);
  };
  visit(source);
}
await writeFile("src/lib/personalization/lumen-copy-keys.ts", `// Generated by scripts/generate-lumen-copy.mjs.\nexport const LUMEN_COPY_KEYS = ${JSON.stringify([...strings].sort(), null, 2)} as const;\n`);
