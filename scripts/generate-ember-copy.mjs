// One-time conversion of static page text into editable copy and regeneration of its catalog.
import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";

const pages = ["pages/home", "pages/menu", "pages/private-dining", "pages/story", "pages/visit", "pages/gift-cards", "pages/reserve", "components/gift-card-form", "components/inquiry-form", "components/reserve-flow", "components/menu-tabs"];
const keys = new Set();
try {
  const previous = await readFile("src/lib/personalization/ember-copy-keys.ts", "utf8");
  const match = previous.match(/export const EMBER_COPY_KEYS = ([\s\S]+) as const;\s*$/);
  if (!match) throw new Error("Cannot parse existing Ember copy catalog");
  for (const value of JSON.parse(match[1])) keys.add(value);
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
for (const name of pages) {
  const file = `src/templates/ember-and-salt/${name}.tsx`;
  let text = await readFile(file, "utf8");
  let source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const edits = [];
  const visit = (node) => {
    if (ts.isJsxText(node)) {
      const value = node.text.replace(/\s+/g, " ").trim();
      // Keep demonstration disclosures fixed and do not turn punctuation into controls.
      if (/[a-zA-Z]/.test(value) && !/sample|demo|no payment|no email|no reservation|no table|allerg/i.test(value)) {
        keys.add(value);
        edits.push({ start: node.getFullStart(), end: node.end, replacement: `{t(${JSON.stringify(value)})}` });
      }
    }
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "t" && node.arguments.length && ts.isStringLiteral(node.arguments[0])) keys.add(node.arguments[0].text);
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (edits.length) {
    for (const edit of edits.sort((a, b) => b.start - a.start)) text = text.slice(0, edit.start) + edit.replacement + text.slice(edit.end);
    text = text.replace(/^\s*"use client";\s*/, "");
    if (!text.includes('import { useEmberCopy }')) text = `import { useEmberCopy } from "../copy";\n${text}`;
    text = `"use client";\n${text}`;
    if (!text.includes("const t = useEmberCopy();")) text = text.replace(/(export function \w+\([^)]*\) \{)/, "$1\n  const t = useEmberCopy();");
    await writeFile(file, text);
  }
}
for (const key of ["Home", "Story", "Hours", "Find us", "Explore", "Prices in pesos, inclusive of VAT. A 10% service charge applies.", "Photo credits", "Getting here", "Two blocks from Kalayaan Avenue. Pay parking at Century City Mall, a five-minute walk. Grab and taxis can stop at the door.", "Dress", "Come as you are. The dining room is warm from the ovens, so leave the jacket in the car.", "Children", "Welcome until 8 pm. We have high chairs and a short kids’ menu from the grill.", "Access", "Step-free entrance and an accessible restroom on the ground floor. The Back Room is up six stairs."]) keys.add(key);
await writeFile("src/lib/personalization/ember-copy-keys.ts", `// Generated by scripts/generate-ember-copy.mjs.\nexport const EMBER_COPY_KEYS = ${JSON.stringify([...keys].sort(), null, 2)} as const;\n`);
